    @staticmethod
    def _build_service_names_section(
        raw_list: Any,
        substring: Optional[str],
        limit: int,
    ) -> ServiceNamesSection:
        items_raw = raw_list if isinstance(raw_list, list) else []
        matching = [
            r for r in items_raw
            if isinstance(r, dict) and _name_matches(r.get("name"), substring)
        ]
        matching.sort(key=lambda r: (r.get("name") or "").lower())
        total = len(matching)
        truncated = matching[:limit]

        items: List[ServiceNameSummary] = []
        for r in truncated:
            raw_type = r.get("serviceType") or r.get("service_type")
            normalized_type: Optional[str]
            if isinstance(raw_type, str):
                lowered = raw_type.strip().lower().replace("-", "_").replace(" ", "_")
                if "server" in lowered and "sequence" in lowered:
                    normalized_type = "server_sequence"
                elif "allowed" in lowered or "protocol" in lowered:
                    normalized_type = "allowed_protocols"
                else:
                    normalized_type = None
            else:
                normalized_type = None
            items.append(
                ServiceNameSummary(
                    name=r.get("name") or "",
                    service_type=normalized_type,  # type: ignore[arg-type]
                    is_local_authorization=r.get("isLocalAuthorization"),
                )
            )
        return ServiceNamesSection(
            total_count=total,
            count=len(items),
            has_more=total > len(items),
            items=items,
        )

    @staticmethod
    def _authz_hit_passes_filters(
        hit: AuthorizationRuleHit,
        entry: Dict[str, Any],
        state_filter: str,
        min_hit_counts: Optional[int],
        profile_substring: Optional[str],
        sg_substring: Optional[str],
        name_substring: Optional[str],
    ) -> bool:
        if not _state_filter_matches(hit.state, state_filter):
            return False
        if min_hit_counts is not None and (hit.hit_counts or 0) < min_hit_counts:
            return False
        if not _name_matches(hit.name, name_substring):
            return False
        if not _profile_list_matches(entry.get("profile"), profile_substring):
            return False
        if not _security_group_matches(entry.get("securityGroup"), sg_substring):
            return False
        return True

    # -----------------------------------------------------------------
    # Tool 4 — ise_search_authentication_rules
    # -----------------------------------------------------------------

    async def search_authentication_rules(
        self,
        policy_set_name: Optional[str] = None,
        identity_source_filter: Optional[str] = None,
        state_filter: str = "all",
        min_hit_counts: Optional[int] = None,
        name_substring: Optional[str] = None,
        limit: int = 25,
    ) -> AuthenticationRuleSearchResult:
        validated_limit = validate_limit(limit, max_limit=50)
        validated_state = validate_rule_state_filter(state_filter)
        validated_min_hits = validate_min_hit_counts(min_hit_counts)
        validated_policy_set_name = (
            validate_policy_set_name(policy_set_name) if policy_set_name is not None else None
        )
        validated_identity_source = (
            validate_name_substring(identity_source_filter, field_name="identity_source_filter")
            if identity_source_filter is not None else None
        )
        validated_substring = (
            validate_name_substring(name_substring, field_name="name_substring")
            if name_substring is not None else None
        )

        logger.info(
            "Searching authentication rules",
            policy_set_name=validated_policy_set_name,
            identity_source_filter=validated_identity_source,
            state_filter=validated_state,
            min_hit_counts=validated_min_hits,
            name_substring=validated_substring,
            limit=validated_limit,
        )

        if validated_policy_set_name is not None:
            _, ps_raw = await self._resolve_policy_set_id_by_name(validated_policy_set_name)
            policy_sets_to_scan = [ps_raw]
        else:
            raw_list = await self.get_network_access_policy_set_list()
            if not isinstance(raw_list, list):
                raw_list = []
            sorted_raw = _sort_policy_sets_by_rank([p for p in raw_list if isinstance(p, dict)])
            policy_sets_to_scan = sorted_raw[:_MAX_FAN_OUT_POLICY_SETS]

        tasks = [
            self.get_network_access_authentication_rule_list(str(ps.get("id")))
            for ps in policy_sets_to_scan
            if ps.get("id")
        ]
        per_ps_results = await asyncio.gather(*tasks)

        rules: List[AuthenticationRuleHit] = []
        for ps, ps_rules in zip(policy_sets_to_scan, per_ps_results):
            ps_name = ps.get("name") or ""
            for entry in (ps_rules if isinstance(ps_rules, list) else []):
                if not isinstance(entry, dict):
                    continue
                hit = self._build_authn_rule_hit(entry, policy_set_name=ps_name)
                if not self._authn_hit_passes_filters(
                    hit, entry, validated_state, validated_min_hits,
                    validated_identity_source, validated_substring,
                ):
                    continue
                rules.append(hit)

        total = len(rules)
        truncated = rules[:validated_limit]

        search_filters: Dict[str, Any] = {
            "state_filter": validated_state,
            "limit": validated_limit,
        }
        if validated_policy_set_name is not None:
            search_filters["policy_set_name"] = validated_policy_set_name
        if validated_identity_source is not None:
            search_filters["identity_source_filter"] = validated_identity_source
        if validated_min_hits is not None:
            search_filters["min_hit_counts"] = validated_min_hits
        if validated_substring is not None:
            search_filters["name_substring"] = validated_substring

        return AuthenticationRuleSearchResult(
            search_filters=search_filters,
            total_count=total,
            count=len(truncated),
            has_more=total > len(truncated),
            policy_sets_scanned=len(policy_sets_to_scan),
            rules=truncated,
        )

    @staticmethod
    def _build_authn_rule_hit(entry: Dict[str, Any], *, policy_set_name: str) -> AuthenticationRuleHit:
        rule = entry.get("rule") or {}
        return AuthenticationRuleHit(
            policy_set_name=policy_set_name,
            name=rule.get("name") or "",
            rank=rule.get("rank"),
            state=_normalize_state(rule.get("state")),
            hit_counts=rule.get("hitCounts"),
            identity_source_name=entry.get("identitySourceName"),
            if_auth_fail=entry.get("ifAuthFail"),
            if_user_not_found=entry.get("ifUserNotFound"),
            if_process_fail=entry.get("ifProcessFail"),
            condition_summary=condition_to_summary(rule.get("condition")),
        )

    @staticmethod
    def _authn_hit_passes_filters(
        hit: AuthenticationRuleHit,
        entry: Dict[str, Any],
        state_filter: str,
        min_hit_counts: Optional[int],
        identity_source_substring: Optional[str],
        name_substring: Optional[str],
    ) -> bool:
        if not _state_filter_matches(hit.state, state_filter):
            return False
        if min_hit_counts is not None and (hit.hit_counts or 0) < min_hit_counts:
            return False
        if not _name_matches(hit.name, name_substring):
            return False
        if not _identity_source_matches(entry.get("identitySourceName"), identity_source_substring):
            return False
        return True


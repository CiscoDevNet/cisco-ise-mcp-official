    @staticmethod
    def _build_identity_stores_section(
        raw_list: Any,
        substring: Optional[str],
        limit: int,
    ) -> IdentityStoresSection:
        items_raw = raw_list if isinstance(raw_list, list) else []
        matching = [
            r for r in items_raw
            if isinstance(r, dict) and _name_matches(r.get("name"), substring)
        ]
        matching.sort(key=lambda r: (r.get("name") or "").lower())
        total = len(matching)
        truncated = matching[:limit]
        items = [IdentityStoreSummary(name=r.get("name") or "") for r in truncated]
        return IdentityStoresSection(
            total_count=total,
            count=len(items),
            has_more=total > len(items),
            items=items,
        )


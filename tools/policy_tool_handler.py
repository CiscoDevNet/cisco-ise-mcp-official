# Hard cap on the number of policy sets scanned during a fan-out search
# (Tools 3 and 4) when no specific policy_set_name was provided. Bounds
# tail latency at the cost of completeness; the SLM is informed via
# `policy_sets_scanned` in the result envelope.
_MAX_FAN_OUT_POLICY_SETS = 25



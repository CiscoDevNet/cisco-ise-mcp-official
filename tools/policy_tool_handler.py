def _normalize_state(value: Any) -> Optional[str]:
    """Normalize the ISE state field to a canonical lowercase string.

    ISE returns either a string or an enum-shaped value depending on the
    code path. Returns None when the value is missing or not coercible.
    """
    if value is None:
        return None
    if isinstance(value, str):
        return value.strip().lower() or None
    return str(value).strip().lower() or None


def _state_filter_matches(rule_state: Optional[str], filter_value: str) -> bool:
    if filter_value == "all":
        return True
    return rule_state == filter_value


def _name_matches(name: Optional[str], substring: Optional[str]) -> bool:
    if substring is None:
        return True
    if not name:
        return False
    return substring.lower() in name.lower()


def _profile_list_matches(profile_value: Any, substring: Optional[str]) -> bool:
    """Case-insensitive substring match against any profile name in a list."""
    if substring is None:
        return True
    if not profile_value:
        return False
    needle = substring.lower()
    if isinstance(profile_value, list):
        return any(isinstance(p, str) and needle in p.lower() for p in profile_value)
    if isinstance(profile_value, str):
        return needle in profile_value.lower()
    return False


def _security_group_matches(value: Any, substring: Optional[str]) -> bool:
    if substring is None:
        return True
    if not value:
        return False
    if isinstance(value, str):
        return substring.lower() in value.lower()
    return False


def _identity_source_matches(value: Any, substring: Optional[str]) -> bool:
    if substring is None:
        return True
    if not value:
        return False
    if isinstance(value, str):
        return substring.lower() in value.lower()
    return False


def _build_authn_rule_summary(entry: Dict[str, Any]) -> AuthenticationRuleSummary:
    rule = entry.get("rule") or {}
    return AuthenticationRuleSummary(
        name=rule.get("name") or "",
        rank=rule.get("rank"),
        state=_normalize_state(rule.get("state")),
        hit_counts=rule.get("hitCounts"),
        identity_source_name=entry.get("identitySourceName"),
        if_auth_fail=entry.get("ifAuthFail"),
        if_user_not_found=entry.get("ifUserNotFound"),
        if_process_fail=entry.get("ifProcessFail"),
        condition_summary=condition_to_summary(rule.get("condition")),
    )


def _build_authz_rule_summary(entry: Dict[str, Any]) -> AuthorizationRuleSummary:
    rule = entry.get("rule") or {}
    return AuthorizationRuleSummary(
        name=rule.get("name") or "",
        rank=rule.get("rank"),
        state=_normalize_state(rule.get("state")),
        hit_counts=rule.get("hitCounts"),
        profile=entry.get("profile"),
        security_group=entry.get("securityGroup"),
        condition_summary=condition_to_summary(rule.get("condition")),
    )


def _build_policy_set_summary(raw: Dict[str, Any]) -> PolicySetSummary:
    return PolicySetSummary(
        name=raw.get("name") or "",
        description=raw.get("description"),
        state=_normalize_state(raw.get("state")),
        rank=raw.get("rank"),
        hit_counts=raw.get("hitCounts"),
        is_default=raw.get("default"),
        service_name=raw.get("serviceName"),
        is_proxy=raw.get("isProxy"),
        condition_summary=condition_to_summary(raw.get("condition")),
    )


def _sort_by_rank(entries: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """Sort rule list entries by ``rule.rank`` ascending. Stable for missing ranks."""
    def key(e: Dict[str, Any]) -> int:
        rule = e.get("rule") or {}
        rank = rule.get("rank")
        return rank if isinstance(rank, int) else 1_000_000
    return sorted(entries, key=key)


def _sort_policy_sets_by_rank(items: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    def key(p: Dict[str, Any]) -> int:
        rank = p.get("rank")
        return rank if isinstance(rank, int) else 1_000_000
    return sorted(items, key=key)


